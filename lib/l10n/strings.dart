/// Every word the app shows, in Arabic (default) and English.
/// `{name}` placeholders are filled by [L10n.lookup].
class L10n {
  static const supported = ['ar', 'en'];

  static String lookup(String lang, String key, [Map<String, String>? args]) {
    final table = _strings[lang] ?? _strings['ar']!;
    var s = table[key] ?? _strings['en']![key] ?? key;
    if (args != null) {
      args.forEach((k, v) => s = s.replaceAll('{$k}', v));
    }
    return s;
  }

  static Set<String> keysFor(String lang) => _strings[lang]!.keys.toSet();
}

extension Tr on BuildContext {
  String tr(String key, [Map<String, String>? args]) =>
      L10n.lookup(Localizations.localeOf(this).languageCode, key, args);
}

